"""Generate the models for each sensitive network.

See specs/dbt-model/sensitive-facility-partition.md for the BL clauses this module implements.

A partitioned model's SQL calls its body macro with `network=none`, or sets
`{% set network = none %}` and reads its inputs through `partition_ref()`. For each sensitive
network this script writes a copy of every such model with the network's code in place of
`none`, a copy of its property file, and, for a report, a copy of its report config (BL-012).

    python scripts/generate_sensitive_network_models.py --networks example

In this repo the fixture network is `example`. A deployment runs the copy of this script in
`dbt_packages/tamanu_source_dbt/scripts/` from its own root: the networks then default to the
`sensitive_networks` var in its `dbt_project.yml`, and the models are written into its own
`models/` folder. Generated files are committed, and CI fails when regenerating changes them
(BL-013).
"""

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
MARKER = "Generated by scripts/generate_sensitive_network_models.py"
PARTITION_ARGUMENT = re.compile(r"\bnetwork(\s*)=(\s*)none\b")
GENERATED_NAME = re.compile(r"^(sn_|sensitive-|[a-z]+__sensitive_)")
MAX_NAME_LENGTH = 63

# A report config value that differs for a sensitive network's copy of the report.
CONFIG_REPLACEMENTS = {
    "lab-requests-line-list": [('"LabTestCategoryField"', '"LabTestCategorySensitiveField"')],
    "lab-tests-line-list": [('"LabTestCategoryField"', '"LabTestCategorySensitiveField"')],
}


def network_key(network):
    """A network's key in model names: its code lowercased, each run of other characters as `_`."""
    return re.sub(r"[^a-z0-9]+", "_", network.lower()).strip("_")


def partition_name(model, network):
    """The name of `model`'s counterpart for a network, as the `partition_name()` macro gives it."""
    key = network_key(network)
    if "__" in model:
        prefix, rest = model.split("__", 1)
        return f"{prefix}__sensitive_{key}_{rest}"
    if "-" in model:
        return f"sensitive-{key.replace('_', '-')}-{model}"
    # A base: the short prefix keeps the longest base name within Postgres's 63 characters.
    return f"sn_{key}_{model}"


def is_generated_dir(path):
    return "sensitive" in path.parts


def output_dir(relative_dir):
    """Where a model's copies go: its folder's `sensitive` sibling, or a `sensitive` subfolder."""
    parts = list(relative_dir.parts)
    if "standard" in parts:
        parts[parts.index("standard")] = "sensitive"
        return Path(*parts)
    return relative_dir / "sensitive"


def partitioned_models(models_dir):
    """Every model that takes the partition, as paths relative to `models_dir`."""
    found = []
    for path in sorted(models_dir.rglob("*.sql")):
        relative = path.relative_to(models_dir)
        if is_generated_dir(relative.parent):
            continue
        if PARTITION_ARGUMENT.search(path.read_text(encoding="utf-8")):
            found.append(relative)
    return found


def model_sql(source_sql, source_relative, network):
    body = PARTITION_ARGUMENT.sub(lambda m: f"network{m.group(1)}={m.group(2)}'{network}'", source_sql)
    header = (
        f"{{#- {MARKER} from models/{source_relative.as_posix()}. Do not edit. -#}}\n"
        "{{ config(tags=['restricted']) }}\n"
    )
    return header + body.replace("\r\n", "\n")


def rename_tests(node, model, new_name):
    """Explicitly named tests must stay unique across a model and its copies."""
    for test in node.get("data_tests") or []:
        if not isinstance(test, dict):
            continue
        for arguments in test.values():
            if isinstance(arguments, dict) and arguments.get("name"):
                name = arguments["name"]
                arguments["name"] = name.replace(model, new_name) if model in name else f"{name}__{new_name}"
    for column in node.get("columns") or []:
        rename_tests(column, model, new_name)


def model_properties(source_yml, model, new_name, source_relative):
    document = yaml.safe_load(source_yml)
    nodes = [node for node in document.get("models") or [] if node.get("name") == model]
    if not nodes:
        return None
    node = nodes[0]
    node["name"] = new_name
    rename_tests(node, model, new_name)
    header = f"# {MARKER} from models/{source_relative.with_suffix('.yml').as_posix()}. Do not edit.\n"
    return header + yaml.safe_dump(
        {"version": 2, "models": [node]}, sort_keys=False, allow_unicode=True, width=1000
    )


def report_config(source_json, model, new_name, network):
    for old, new in CONFIG_REPLACEMENTS.get(model, []):
        source_json = source_json.replace(old, new)
    config = json.loads(source_json)
    name = config["name"]
    config["name"] = f"Sensitive {network} {name[:1].lower()}{name[1:]}"
    config["notes"] = (
        f"{config.get('notes', '').rstrip()}\n\n"
        f"This version covers facilities in the '{network}' sensitive network only."
    ).lstrip()
    return json.dumps(config, indent=2, ensure_ascii=False) + "\n"


def config_path(relative_sql):
    """A report's config sits under reports/config/ at the path its SQL has under reports/sql/."""
    parts = list(relative_sql.parts)
    if parts[:2] != ["reports", "sql"]:
        return None
    return Path("reports", "config", *parts[2:]).with_suffix(".json")


def generate(source_models, output_models, networks):
    """Write every network's models under `output_models`, returning the paths written."""
    written = {}
    for relative in partitioned_models(source_models):
        model = relative.stem
        sql = (source_models / relative).read_text(encoding="utf-8")
        yml_path = (source_models / relative).with_suffix(".yml")
        json_relative = config_path(relative)
        for network in networks:
            new_name = partition_name(model, network)
            if len(new_name) > MAX_NAME_LENGTH:
                sys.exit(
                    f"{new_name} is {len(new_name)} characters, and Postgres allows {MAX_NAME_LENGTH}. "
                    f"Give the sensitive network '{network}' a shorter code."
                )
            target = output_dir(relative.parent) / new_name
            written[target.with_suffix(".sql")] = model_sql(sql, relative, network)
            if yml_path.exists():
                properties = model_properties(yml_path.read_text(encoding="utf-8"), model, new_name, relative)
                if properties:
                    written[target.with_suffix(".yml")] = properties
            if json_relative and (source_models / json_relative).exists():
                source_json = (source_models / json_relative).read_text(encoding="utf-8")
                json_target = output_dir(json_relative.parent) / f"{new_name}.json"
                written[json_target] = report_config(source_json, model, new_name, network)

    # Remove what an earlier run wrote for a network or model that is gone. A generated model or
    # property file carries the marker, and a generated report config sits beside neither, so it
    # is recognised by the generated report it belongs to.
    stale_reports = set()
    for path in sorted(output_models.rglob("*")):
        relative = path.relative_to(output_models)
        if not path.is_file() or path.suffix not in (".sql", ".yml") or relative in written:
            continue
        if not is_generated_dir(relative.parent) or not GENERATED_NAME.match(path.name):
            continue
        if MARKER in path.read_text(encoding="utf-8"):
            if config_path(relative):
                stale_reports.add(output_models / config_path(relative))
            path.unlink()
    for path in stale_reports:
        if path.exists() and path.relative_to(output_models) not in written:
            path.unlink()

    for relative, content in written.items():
        path = output_models / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return sorted(written)


def project_networks(project_root):
    project = yaml.safe_load((project_root / "dbt_project.yml").read_text(encoding="utf-8"))
    listed = (project.get("vars") or {}).get("sensitive_networks") or []
    if isinstance(listed, str):
        listed = [code.strip() for code in listed.split(",") if code.strip()]
    return list(listed)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--networks", nargs="*", help="sensitive network codes (default: the project's var)")
    parser.add_argument("--source", type=Path, default=PACKAGE_ROOT, help="the tamanu-source-dbt checkout")
    parser.add_argument("--output", type=Path, default=Path.cwd(), help="the project to write models into")
    args = parser.parse_args(argv)

    networks = args.networks if args.networks is not None else project_networks(args.output)
    keys = [network_key(network) for network in networks]
    if len(set(keys)) != len(keys) or "" in keys:
        sys.exit(f"Sensitive network codes must give distinct, non-empty keys: {networks}")

    written = generate(args.source / "models", args.output / "models", networks)
    print(f"Wrote {len(written)} files for {len(networks)} sensitive network(s): {', '.join(networks) or 'none'}")


if __name__ == "__main__":
    main()
