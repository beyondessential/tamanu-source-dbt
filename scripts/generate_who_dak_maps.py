"""Generate the WHO DAK element dictionary and question map models from their CSV copies.

tupaia-data-product generates each DAK domain's element dictionary and question map and owns
them; csv/who_dak/ holds byte-identical copies. Each copy becomes a view over a values list in
models/maps/who_dak/, so it reaches a deployment through the package and the compiled bundle
without `dbt seed`.

See specs/dbt-model/map__who_dak.md for the BL clauses this module implements.

Run from the repo root after updating a copy:
    python scripts/generate_who_dak_maps.py
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

CSV_DIR = Path("csv") / "who_dak"
MODELS_DIR = Path("models") / "maps" / "who_dak"

COLUMNS = {
    "elements": ("element_id", "label", "data_type", "tab"),
    "questions": ("survey_id", "question_code", "option", "element_id", "role"),
}

NAME = re.compile(r"^map__who_dak_[a-z0-9_]+_(elements|questions)$")


def sql_literal(value: str) -> str:
    # BL-003: a blank cell reads NULL
    if value == "":
        return "null"
    return "'" + value.replace("'", "''") + "'"


def read_copy(path: Path) -> tuple[str, list[dict]]:
    """The copy's kind and its rows, refusing a file the models could not be built from."""
    match = NAME.match(path.stem)
    if not match:
        raise ValueError(f"{path}: not named map__who_dak_<domain>_elements or _questions")
    kind = match.group(1)
    with path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        if tuple(reader.fieldnames or ()) != COLUMNS[kind]:
            raise ValueError(f"{path}: columns {reader.fieldnames} are not {list(COLUMNS[kind])}")
        rows = list(reader)
    # An empty values list is invalid SQL that would only fail at `dbt run`
    if not rows:
        raise ValueError(f"{path}: no rows")
    return kind, rows


def build_model(name: str, kind: str, rows: list[dict]) -> str:
    """The model SQL for one copy: every row in the copy's order, every column text."""
    columns = COLUMNS[kind]
    # BL-002: every column is text, so a column that is NULL in every row is still typed
    select_list = ",\n".join(f"    {column}::text as {column}" for column in columns)
    # laid out as the repo's sqlfluff config expects, so the models lint like hand-written ones
    values = ",\n".join(
        "    (" + ", ".join(sql_literal(row[column]) for column in columns) + ")" for row in rows
    )
    return f"""-- Generated from csv/who_dak/{name}.csv by scripts/generate_who_dak_maps.py.
-- DO NOT EDIT THIS FILE MANUALLY: update the copy from tupaia-data-product and regenerate.

select
{select_list}
from (
    values
{values}
) t ({", ".join(columns)})
"""


def generate(csv_dir: Path = CSV_DIR, models_dir: Path = MODELS_DIR) -> list[Path]:
    """Write one model per copy, and remove a generated model whose copy is gone."""
    # BL-001: the copies are read as committed, never rewritten here
    copies = sorted(csv_dir.glob("map__who_dak_*.csv"))
    if not copies:
        raise ValueError(f"no copies in {csv_dir}")
    models_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for path in copies:
        kind, rows = read_copy(path)
        # BL-002: one view per copy, named as the copy
        target = models_dir / f"{path.stem}.sql"
        # newline="": the models are committed, so a CRLF rewrite would show as drift in CI
        with target.open("w", encoding="utf-8", newline="") as handle:
            handle.write(build_model(path.stem, kind, rows))
        written.append(target)
    for stale in set(models_dir.glob("map__who_dak_*.sql")) - set(written):
        stale.unlink()
    return written


def main() -> int:
    try:
        written = generate()
    except ValueError as error:
        print(f"Error: {error}")
        return 1
    for path in written:
        print(f"Generated {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
